'use strict';
const assert=require('node:assert/strict');
const list=require('../assets/shared-dataset-list.js');
const id='synthetic_shared_file_123', other='synthetic_shared_file_456';
const original=list.change(list.empty(),id,'One','device-a');
const left=list.change(original,id,'Renamed','device-a');
const right=list.change(original,id,null,'device-b');
assert.equal(list.merge(left,right).items[0].deleted,true,'Concurrent removal wins over rename');
assert.deepEqual(list.merge(left,right),list.merge(right,left),'Merging is deterministic');
assert.equal(list.merge(original,right).items[0].deleted,true,'An old device cannot resurrect a removal');
const readded=list.change(right,id,'Added again','device-a');
assert.equal(list.merge(right,readded).items[0].deleted,false,'Explicit re-add after seeing removal is supported');
assert.equal(list.merge(original,list.change(list.empty(),other,'Two','device-b')).items.length,2,'Different-device additions are kept');
assert.deepEqual(list.merge(original,original),original,'Repeated sync is idempotent');
assert.throws(()=>list.validate({...original,version:2}),/supported version/);
assert.throws(()=>list.validate({...original,items:[...original.items,...original.items]}),/invalid reference/);
assert.throws(()=>list.change(original,'https://evil.test/','Bad','device-a'),/invalid reference/);
assert.throws(()=>list.change(original,id,'x'.repeat(121),'device-a'),/invalid reference/);
const unknown={...original,access_token:'must-not-travel',entries:[{comment:'private'}]};
assert.deepEqual(list.validate(unknown),original,'Records, tokens and unrelated fields cannot be copied into shared-list output');
assert.equal(right.items[0].label,'','Removed aliases are cleared from tombstones');
console.log('PASS: shared references merge deterministically; deletions survive stale devices, additions and explicit re-adds survive, and data/tokens are excluded.');
